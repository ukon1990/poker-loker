const BY_ID = new Map(GLOSSARY.map((term) => [term.id, term]));

export function getTerm(id: string): GlossaryTerm {
  const term = BY_ID.get(id);
  if (!term) throw new Error(`Unknown glossary term: ${id}`);
  return term;
}

export function hasTerm(id: string): boolean {
  return BY_ID.has(id);
}
